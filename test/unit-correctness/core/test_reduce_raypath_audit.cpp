// Audit tests for Crystal::ReduceRaypath orbit invariant property.
//
// Background (scratchpad/scrum-filter-architecture-refactor/explore-reduce-raypath-audit/):
//   Task #209 fixed sigma_a≠0 + P+D canonicalization but covered only one case.
//   This audit systematically verifies orbit invariant across 5 dimensions:
//     H1: prism + kSymP + sigma_a≠0
//     H2: kSymB (basal 1↔2 + pyramid upper↔lower)
//     H3: pyramid crystal (双位编码 face_id 13..18/23..28)
//     H4: multi-segment (rp.size up to kMaxHits=8)
//     H5: mixed crystal type config
//     H6: low-symmetry shapes (non-uniform face distances, unequal cones) — the reduction must
//         use only the symmetry elements the crystal's shape really has
//
// Orbit invariant property:
//   For any raypath rp and any g in the symmetry group G generated by the active
//   symmetries, ReduceRaypath(rp) == ReduceRaypath(g·rp). The orbit {g·rp : g ∈ G}
//   is enumerated via Crystal::ExpandRaypath. Every orbit member must reduce to
//   the same canonical representative.
//
// On failure: this audit produces a minimal repro (failing orbit member + the two
// distinct canonicals) — the same pattern as #209's fix scope.

#include <gtest/gtest.h>

#include <algorithm>
