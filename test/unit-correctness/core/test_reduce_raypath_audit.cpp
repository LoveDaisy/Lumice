TEST(H6_LowSymmetryShape_Audit, PrismShapesAgainstTheFacePlaneOracle) {
  const float kDists[][6] = {
    { 1.0f, 1.0f, 1.0f, 1.0f, 1.0f, 1.0f },  // six-fold, all mirrors
    { 1.0f, 1.2f, 1.0f, 1.2f, 1.0f, 1.2f },  // three-fold (p_step 2), even mirrors
    { 1.0f, 1.0f, 1.3f, 1.0f, 1.0f, 1.3f },  // two-fold (p_step 3)
    { 1.0f, 1.2f, 1.3f, 1.3f, 1.2f, 1.0f },  // one mirror only (sigma_a = 5)
    { 1.0f, 1.1f, 1.2f, 1.3f, 1.4f, 1.5f },  // nothing but B
  };
  for (const auto& dist : kDists) {
    const Crystal c = Crystal::CreatePrism(0.8f, dist);
    SCOPED_TRACE("dist = {" + std::to_string(dist[0]) + ", " + std::to_string(dist[1]) + ", " +
                 std::to_string(dist[2]) + ", " + std::to_string(dist[3]) + ", " + std::to_string(dist[4]) + ", " +
                 std::to_string(dist[5]) + "}");
    EXPECT_TRUE(VerifyDerivedFields(c));
    EXPECT_TRUE(VerifyAgainstShapeOracle(c, kPrismFaces, 20260927u));
  }
}

TEST(H6_LowSymmetryShape_Audit, PyramidShapesAgainstTheFacePlaneOracle) {
  const float kRegular[6]{ 1.0f, 1.0f, 1.0f, 1.0f, 1.0f, 1.0f };
  const float kThreeFold[6]{ 1.0f, 1.2f, 1.0f, 1.2f, 1.0f, 1.2f };
  struct Case {
    const char* what;
    float alpha_u, alpha_l, h1, h2, h3;
    const float* dist;
    bool expect_b;
  };
  const Case kCases[] = {
    { "symmetric cones, three-fold section", 28.0f, 28.0f, 0.4f, 1.0f, 0.4f, kThreeFold, true },
    { "unequal wedge angles", 28.0f, 40.0f, 0.4f, 1.0f, 0.4f, kRegular, false },
    { "unequal cone heights", 28.0f, 28.0f, 0.3f, 1.0f, 0.6f, kRegular, false },
    { "upper cone only", 28.0f, 28.0f, 0.4f, 1.0f, 0.0f, kRegular, false },
  };
  for (const auto& k : kCases) {
    SCOPED_TRACE(k.what);
    const Crystal c = Crystal::CreatePyramid(k.alpha_u, k.alpha_l, k.h1, k.h2, k.h3, k.dist);
    if (c.PolygonFaceCount() == 0) {
      ADD_FAILURE() << "degenerate crystal: the case exercises nothing";
      continue;
    }
    EXPECT_EQ(c.GeomSymmetry().b_applicable, k.expect_b);
    EXPECT_TRUE(VerifyDerivedFields(c));
    EXPECT_TRUE(VerifyAgainstShapeOracle(c, kPyramidFaces, 20260928u));
  }
}

